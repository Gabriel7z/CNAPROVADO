function incidenciaConcursos() {
  const seen = [];
  INCIDENCIA.forEach((i) => {
    if (!seen.some((s) => s.id === i.concurso)) {
      seen.push({ id: i.concurso, nome: i.concursoNome });
    }
  });
  return seen;
}

function incidenciaMaterias(concurso) {
  return INCIDENCIA.filter((i) => i.concurso === concurso).map((i) => ({
    id: i.materia,
    nome: i.materiaNome,
  }));
}

function incidenciaRecorte(concurso, materia) {
  const item = INCIDENCIA.find((i) => i.concurso === concurso && i.materia === materia);
  return item ? incidenciaComPct(item) : null;
}

