function incidenciaComPct(item) {
  const total = item.topicos.reduce((s, t) => s + t[1], 0);
  let acc = 0;
  let cruzou70 = false;
  const topicos = item.topicos.map(([nome, q]) => {
    const pct = total ? Math.round((1000 * q) / total) / 10 : 0;
    acc = Math.min(100, Math.round((acc + pct) * 10) / 10);
    const prio = !cruzou70;
    if (acc >= 70) cruzou70 = true;
    return { nome, q, pct, acc, prio };
  });
  return { ...item, total, topicos };
}

function incidenciaConcursos() {
  const seen = [];
  INCIDENCIA.forEach((i) => {
    if (!seen.some((s) => s.id === i.concurso)) {
      seen.push({ id: i.concurso, nome: i.concursoNome });
    }
  });
  return seen;
}

function incidenciaMaterias(concurso) {
  return INCIDENCIA.filter((i) => i.concurso === concurso).map((i) => ({
    id: i.materia,
    nome: i.materiaNome,
  }));
}

function incidenciaRecorte(concurso, materia) {
  const item = INCIDENCIA.find((i) => i.concurso === concurso && i.materia === materia);
  return item ? incidenciaComPct(item) : null;
}

